#!/usr/bin/env python3
"""Download the page's two fonts once and write vendor/fonts/fonts.css with the woff2 files
embedded as data URIs, so the simulator needs no network at all.

Fonts (both SIL Open Font License 1.1): Atkinson Hyperlegible (Braille Institute) 400, 400 italic, 700;
IBM Plex Mono (IBM) 400, 500, 600. Only the Latin subset is kept: the page is English.

Run:  python embed_fonts.py      (needs internet once; build.sh then works offline)
"""
import base64, re, urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
FONTS = HERE.parent / "vendor" / "fonts"
CSS_URL = ("https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400"
           "&family=IBM+Plex+Mono:wght@400;500;600&display=swap")
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"


def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30).read()


FONTS.mkdir(parents=True, exist_ok=True)
css = get(CSS_URL).decode()
out = ["/* GENERATED by tools/embed_fonts.py - Atkinson Hyperlegible and IBM Plex Mono, SIL OFL 1.1, Latin subset */"]
for block in re.findall(r"/\* latin \*/\s*(@font-face\s*{[^}]*})", css):
    fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
    style = re.search(r"font-style:\s*(\w+)", block).group(1)
    weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
    url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
    name = f"{fam.replace(' ', '')}-{weight}{'i' if style == 'italic' else ''}.woff2"
    data = get(url); (FONTS / name).write_bytes(data)
    uri = "data:font/woff2;base64," + base64.b64encode(data).decode()
    out.append(f"@font-face{{font-family:'{fam}';font-style:{style};font-weight:{weight};font-display:swap;src:url({uri}) format('woff2');}}")
    print(f"{name:40s} {len(data)/1024:6.1f} KB")
(FONTS / "fonts.css").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", FONTS / "fonts.css")
